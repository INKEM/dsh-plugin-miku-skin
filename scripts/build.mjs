/**
 * Build the browser bundle and copy the host half.
 *
 * The client source is plain CJS-style JavaScript that uses `require` for the
 * platform-provided React seed; this script only wraps it in DSH's lazy module
 * envelope and substitutes the compiled stylesheet. No dependencies, no
 * network, and no output rewrite when nothing changed (so an idle `npm run
 * build` never triggers a client HMR reload).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const pluginId = pkg.name
const css = readFileSync(join(root, 'src/client/styles.css'), 'utf8')
const source = readFileSync(join(root, 'src/client/index.js'), 'utf8')
const host = readFileSync(join(root, 'src/index.js'), 'utf8')

const placeholder = '__MIKU_CSS__'
const occurrences = source.split(placeholder).length - 1
if (occurrences !== 1) {
  throw new Error(`src/client/index.js must reference ${placeholder} exactly once (found ${occurrences})`)
}
if (/\b(?:import|export)\s/.test(source)) {
  throw new Error('src/client/index.js must stay CJS-style: the module envelope provides require/exports')
}

const inlined = source.split(placeholder).join(JSON.stringify(css))
const bundle = `/* ${pluginId} client bundle — generated by scripts/build.mjs; edit src/client/* instead. */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pluginId)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${inlined}
\t\treturn module.exports;
\t}
});
`

const hostOutput = `/* ${pluginId} host half — generated by scripts/build.mjs; edit src/index.js instead. */
${host}`

function writeIfChanged(file, content) {
  let previous = null
  try {
    previous = readFileSync(file, 'utf8')
  } catch {
    previous = null
  }
  if (previous === content) {
    console.log(`unchanged ${file.slice(root.length + 1)} (${Buffer.byteLength(content)} bytes)`)
    return
  }
  writeFileSync(file, content)
  console.log(`wrote     ${file.slice(root.length + 1)} (${Buffer.byteLength(content)} bytes)`)
}

writeIfChanged(join(root, 'lib/client.js'), bundle)
writeIfChanged(join(root, 'lib/index.js'), hostOutput)
